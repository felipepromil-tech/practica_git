#calcular la area de el triangulo y el cuadrado
def triangulo (base, altura):
    area = (base * altura) / 2 #calculo extacto del area del triangulo
    return area # usos posteriores terminar funcion
#Calculo del area del cuadrado

def cuadrado (lado):
    area = lado * lado #calculo extacto triangulo
    return area # para usos posteriores y terminar funcion



